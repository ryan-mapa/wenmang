// Generates source/character-data.js from the Unicode Unihan database.
//
// Run it when the decks change:
//
//   curl -O https://www.unicode.org/Public/UCD/latest/ucd/Unihan.zip
//   unzip -d /tmp/unihan Unihan.zip
//   node tools/build-characters.mjs /tmp/unihan
//
// Unihan is not vendored. It is 8MB to get two small numbers per character, and
// the generated table is a few kilobytes — so the table is committed and the
// source is fetched on demand. The Unicode license is permissive enough that
// vendoring would be fine; this is a size decision, not a licensing one.
//
// Two fields are read, and neither is a guess:
//
//   kRSUnicode    the Kangxi radical, and how many strokes are left once the
//                 radical is removed. '140.5' is radical 140 (艹) plus five.
//                 A prime — "140'.5" — marks a simplified radical form.
//   kTotalStrokes how many strokes the whole character takes to write.
//
// Together they give the hint ladder its first two rungs without needing any
// stroke geometry: how long is this character, and what family is it from.

import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { DECKS } from '../source/vocab.js';

const here = dirname(fileURLToPath(import.meta.url));
const unihanDir = process.argv[2];

if (!unihanDir) {
  console.error('usage: node tools/build-characters.mjs <path-to-unpacked-unihan>');
  process.exit(1);
}

/** Han characters only — pinyin and punctuation in a deck are not characters to learn. */
const isHan = (ch) => /\p{Script=Han}/u.test(ch);

function charactersInDecks() {
  const seen = new Set();
  for (const deck of DECKS) {
    for (const word of deck.stages.flat()) {
      for (const ch of word.zh) if (isHan(ch)) seen.add(ch);
    }
  }
  return [...seen].sort();
}

/** Parse the tab-separated Unihan format: `U+82F9\tkRSUnicode\t140.5`. */
function readUnihan(file, fields) {
  const out = new Map();
  const text = readFileSync(join(unihanDir, file), 'utf8');
  for (const line of text.split('\n')) {
    if (!line || line.startsWith('#')) continue;
    const [code, field, value] = line.split('\t');
    if (!fields.has(field)) continue;
    const ch = String.fromCodePoint(Number.parseInt(code.slice(2), 16));
    if (!out.has(ch)) out.set(ch, {});
    out.get(ch)[field] = value?.trim();
  }
  return out;
}

const wanted = charactersInDecks();
const unihan = readUnihan('Unihan_IRGSources.txt', new Set(['kRSUnicode', 'kTotalStrokes']));

const table = {};
const missing = [];

for (const ch of wanted) {
  const entry = unihan.get(ch);
  // kRSUnicode can list more than one analysis; the first is the normative one.
  const rs = entry?.kRSUnicode?.split(' ')[0];
  const strokes = Number.parseInt(entry?.kTotalStrokes?.split(' ')[0] ?? '', 10);

  if (!rs || !Number.isFinite(strokes)) {
    missing.push(ch);
    continue;
  }

  // "140'.5" — the prime means the simplified form of the radical.
  const [radicalPart, residualPart] = rs.split('.');
  table[ch] = {
    radical: Number.parseInt(radicalPart, 10),
    simplifiedRadical: radicalPart.includes("'"),
    residual: Number.parseInt(residualPart, 10),
    strokes
  };
}

const body = Object.entries(table)
  .map(([ch, d]) =>
    `  '${ch}': { radical: ${d.radical}, simplifiedRadical: ${d.simplifiedRadical}, ` +
    `residual: ${d.residual}, strokes: ${d.strokes} }`
  )
  .join(',\n');

const file = `// GENERATED by tools/build-characters.mjs — do not edit by hand.
//
// Source: Unicode Han Database (Unihan), fields kRSUnicode and kTotalStrokes.
// Unicode data is used under the Unicode License; see NOTICE.
//
// radical           Kangxi radical number, 1..214
// simplifiedRadical the radical appears in its simplified form
// residual          strokes remaining once the radical is removed
// strokes           strokes in the whole character

export const CHARACTER_DATA = {
${body}
};
`;

writeFileSync(join(here, '..', 'source', 'character-data.js'), file);
console.log(`wrote ${Object.keys(table).length} characters`);
if (missing.length) console.warn(`no Unihan entry for: ${missing.join(' ')}`);
