// depth. Seven decks are deliberately smaller, and for the same reasons its
// are — Numbers Basics *is* 0–20, and Questions & Connectors is a closed class
// throughout. Padding those to a round number would mean inventing filler.
//
// NOT YET REVIEWED BY A NATIVE SPEAKER. The tones are machine-checked against
// Unihan and the glosses were written to be the plainest common equivalent,
// but register and naturalness need a human read.

