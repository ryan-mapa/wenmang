// The `zh` string is the progress key, so it is a stable identifier before it
// is a display string: never rewrite one that has shipped, or you silently
// orphan every card anyone has built on it. Add a new entry and retire the old
// one instead. Moving a word between stages is safe — the key does not change,
// and the stage is only where the word sits.
//
// Pinyin carries tone marks rather than tone numbers. It is shown to the
// learner, and `ni3 hao3` is not something anybody reads aloud. Tones are
// checked against the Unicode Han Database by tools/check-vocab.mjs, one
// syllable per character; a wrong tone is the error nobody catches by eye and
// the one that teaches somebody to say a word wrong for years.
//
// A word that appears in two decks — 鱼 is both food and an animal — is one
// card, met in two places. Both entries must then gloss it identically, or the
// same card teaches two different answers depending on where you met it. The
// checker enforces this.
//
